#!/usr/bin/env node
// Native Codex registrations derived from the canonical runner-neutral policy.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(process.env.AGENT_CONFIG_ROOT || path.join(path.dirname(fileURLToPath(import.meta.url)), "../.."));
const quote = (value) => JSON.stringify(value);

export function registrations(rootDir) {
  const load = (name) => JSON.parse(fs.readFileSync(path.join(rootDir, name), "utf8"));
  const neutral = load(".agents/hooks.json");
  const reviewers = load(".agents/subagents.json").subagents;
  const context7 = load(".mcp.json").mcpServers.context7;
  const command = (event) => {
    const dispatch = `bash "$(git rev-parse --show-toplevel)/scripts/with-host-python.sh" python3 "$(git rev-parse --show-toplevel)/tools/agent-config/codex_hook.py" ${event}`;
    // Codex continues after ordinary hook crashes. Include the shell/Python startup boundary
    // in the blocking contract, before the Python adapter can emit its native decision.
    return ["PreToolUse", "Stop"].includes(event)
      ? `${dispatch} || { echo "Project Codex ${event} bootstrap failed; verification is blocked." >&2; exit 2; }`
      : dispatch;
  };
  const handler = (event, timeout, statusMessage, matcher) => ({
    ...(matcher ? { matcher } : {}),
    hooks: [{ type: "command", command: command(event), timeout, statusMessage }],
  });
  const guard = neutral["pre-tool-guards"].PreToolUse;
  const matcher = `^(?:${guard.map((group) => group.matcher.slice(1, -1)).join("|")})$`;
  const hooks = {
    description: "Generated by tools/agent-config/sync-codex.mjs from .agents; review and trust in Codex before use.",
    hooks: {
      SessionStart: [handler("SessionStart", 20, "Detecting repository capabilities", "startup|resume|clear|compact")],
      SubagentStart: [handler("SubagentStart", 15, "Loading repository reviewer boundaries")],
      PreToolUse: [handler("PreToolUse", 200, "Checking project safety and current PR evidence", matcher)],
      PostToolUse: [handler("PostToolUse", 30, "Formatting edited first-party C and C++", neutral["post-tool-formatter"].PostToolUse[0].matcher)],
      Stop: [handler("Stop", 600, "Running changed host logic tests")],
    },
  };
  const files = new Map([
    [".codex/hooks.json", JSON.stringify(hooks, null, 2) + "\n"],
    [".codex/config.toml", "# Generated by tools/agent-config/sync-codex.mjs; canonical MCP source: .mcp.json.\n" +
      "# Project trust and hook trust remain user decisions; no permission defaults are broadened.\n" +
      "[agents]\nenabled = true\n\n[mcp_servers.context7]\n" +
      `command = ${quote(context7.command)}\nargs = ${quote(context7.args)}\nstartup_timeout_sec = 30\n`],
  ]);
  for (const reviewer of reviewers) {
    if (!/^[a-z][a-z0-9_]*$/.test(reviewer.TypeName) || reviewer.SandboxMode !== "read-only")
      throw new Error("canonical Codex reviewer must have a safe name and read-only sandbox");
    files.set(`.codex/agents/${reviewer.TypeName}.toml`,
      "# Generated from .agents/subagents.json; edit the canonical prompt, then regenerate.\n" +
      `name = ${quote(reviewer.TypeName)}\ndescription = ${quote(reviewer.Description)}\n` +
      'sandbox_mode = "read-only"\napproval_policy = "never"\n' +
      `developer_instructions = ${quote(reviewer.Prompt)}\n`);
  }
  return files;
}

try {
  const files = registrations(root);
  const write = process.argv.includes("--write");
  for (const [name, contents] of files) {
    const target = path.join(root, name);
    for (let probe = target; probe !== root; probe = path.dirname(probe)) {
      try {
        if (fs.lstatSync(probe).isSymbolicLink()) throw new Error(`unsafe native Codex registration path: ${name}`);
      } catch (error) { if (error.code !== "ENOENT") throw error; }
    }
    if (write) {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, contents);
    } else if (!fs.existsSync(target) || fs.lstatSync(target).isSymbolicLink() || fs.readFileSync(target, "utf8") !== contents) {
      throw new Error(`native Codex registration missing or drifted: ${name}`);
    }
  }
  const expected = [...files.keys()].filter((name) => name.startsWith(".codex/agents/")).map((name) => path.basename(name)).sort();
  const actual = fs.readdirSync(path.join(root, ".codex/agents")).sort();
  if (JSON.stringify(expected) !== JSON.stringify(actual)) throw new Error("native Codex reviewer inventory drifted");
  console.log(`codex-config: ${files.size} native registrations ${write ? "generated" : "verified"}`);
} catch (error) {
  console.error(`codex-config: ${error.message}`);
  process.exit(1);
}
